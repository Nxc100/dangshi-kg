# 错字/同音干扰用的同音字替换表(替换后拼音不变，可由三级链接的同音纠错级召回)
HOMOPHONES = {
    "遵": "尊", "义": "议", "泽": "则", "东": "冬", "会": "汇", "昌": "倡", "起": "企",
    "征": "争", "延": "严", "安": "按", "南": "难", "毛": "矛", "周": "州", "恩": "摁",
    "来": "莱", "党": "档", "代": "带", "表": "标", "大": "达", "战": "站", "役": "意",
    "军": "均", "长": "常", "国": "果", "共": "公", "产": "铲", "中": "忠", "华": "划",
    "人": "仁", "民": "敏", "革": "隔", "命": "明", "西": "锡", "运": "孕", "动": "栋",
}


def perturb(name):
    """把实体名中的一个字换成同音字，模拟用户打错字；无可替换字时原样返回。"""
    for index, char in enumerate(name):
        if char in HOMOPHONES:
            return name[:index] + HOMOPHONES[char] + name[index + 1:]
    return name
