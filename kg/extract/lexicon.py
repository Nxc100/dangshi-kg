def is_org(name):
    """按后缀判定是否为完整机构名；单字后缀需四字起，以避开同形普通词。"""
    if name in ORG_STOP or not (3 <= len(name) <= 30) or NOT_ORG.search(name):
        return False
    return bool(ORG_TAIL_LONG.search(name)) or (len(name) >= 4 and bool(ORG_TAIL_SHORT.search(name)))


def is_place(name):
    """按政区后缀或人工登记表判定是否为地名；两字地名只认人工登记表。"""
    if name in PLACE_STOP or not (2 <= len(name) <= 20) or NOT_PLACE.search(name):
        return False
    if name in KNOWN_PLACES:
        return True
    return len(name) >= 3 and bool(PLACE_TAIL.search(name))


def doc_type_of(name):
    """按名称后缀判定文献类型，落不到规则上时归为「文章」。"""
    for pattern, value in DOC_TYPE_RULES:
        if pattern.search(name):
            return value
    return DOC_TYPE_DEFAULT


def is_document(name):
    """书名号内跨度是否可作文献收录（排除报刊名与过长过短的跨度）。"""
    return (DOC_MIN <= len(name) <= DOC_MAX
            and name not in DOC_GENERIC
            and not DOC_STOP_TAIL.search(name)
            # 名称内含空格说明原文在此处有被剥除的标记，跨度不完整
            and not any(ch.isspace() for ch in name)
            and "，" not in name and "。" not in name)
